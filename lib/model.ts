// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the floor that the same visible filters keep: the early rows the radar
// exists to find. A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol); the live-token protocols are kept apart and shown with the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, never from a list of names:
//
//   multiple   = the category's median market-cap-to-TVL ratio over the live protocols that
//                already trade (at least 3 comparables), else the whole market's median; clamped
//                to [0.05, 1.5]. A category whose tokens the market already values richly against
//                their TVL gives its pre-token peers a richer multiple.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains - 1, 5)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// The same function scores every row. No protocol name is ever special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

